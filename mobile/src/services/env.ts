// Única leitura de process.env do app. O Expo só troca `process.env.EXPO_PUBLIC_X`
// pelo valor quando o acesso é literal e estático (sem colchetes nem
// desestruturação), então cada variável aparece escrita por extenso. O teste
// `services.test.mjs` garante que esta lista e o `.env.example` não divergem.
// Tudo aqui vai para o pacote do app e fica visível: nunca coloque segredo.
export type RawEnv = Record<string, string | undefined>;

