    EXPO_PUBLIC_API_CANDIDATES_GET: process.env.EXPO_PUBLIC_API_CANDIDATES_GET,
    EXPO_PUBLIC_API_MESSAGES_GET: process.env.EXPO_PUBLIC_API_MESSAGES_GET,
    EXPO_PUBLIC_API_HISTORY_GET: process.env.EXPO_PUBLIC_API_HISTORY_GET,
